"use client";

import { useState } from "react";
import type { DealWorkspaceDTO } from "@/types/contracts";
import { defaultOfferTerms } from "@/lib/deal-defaults";
import type { MandateInput } from "@/lib/mock/types";
import { useMockData } from "@/providers/MockDataProvider";
import { Alert } from "@/components/ui/Alert";
import { Button } from "@/components/ui/Button";
import { Card, CardBody, CardHeader } from "@/components/ui/Card";
import { EmptyState } from "@/components/ui/EmptyState";
import { MandateBuilderForm } from "@/components/forms/MandateBuilderForm";
import { OfferForm } from "@/components/forms/OfferForm";
import { MandateSummary } from "./MandateSummary";
import { OfferComparison } from "./OfferComparison";

interface Feedback {
  tone: "success" | "error" | "warning" | "info";
  message: string;
}

export function NegotiationPanel({
  workspace,
  onOpenAgreement,
}: {
  workspace: DealWorkspaceDTO;
  onOpenAgreement: () => void;
}) {
  const { actions } = useMockData();
  const [editingMandate, setEditingMandate] = useState(false);
  const [busy, setBusy] = useState<string | null>(null);
  const [feedback, setFeedback] = useState<Feedback | null>(null);

  const frozen = workspace.status === "DISPUTED" || workspace.disputeStatus === "OPEN";
  const activeNegotiation = workspace.status === "ACTIVE_NEGOTIATION" && !frozen;
  const termsPending = workspace.status === "TERMS_PENDING_ACCEPTANCE" && !frozen;
  const canEditMandate = !frozen && (workspace.status === "ACTIVE_NEGOTIATION" || termsPending);
  const initialTerms = defaultOfferTerms(workspace);

  async function saveMandate(input: MandateInput) {
    const mandate = await actions.saveMandate(workspace.dealId, input);
    setEditingMandate(false);
    setFeedback({
      tone: "success",
      message: `Mandate v${mandate.version} locked for your ${mandate.partyRole.toLowerCase()} account. In demo mode this is a local simulation.`,
    });
  }

  async function submitOffer(terms: Parameters<typeof actions.submitOffer>[1], message: string) {
    const offer = await actions.submitOffer(workspace.dealId, terms, message);
    setFeedback({
      tone: "success",
      message: `Round ${offer.roundNumber} offer recorded in the demo workspace. Live mode would show the server's offer ID and score.`,
    });
  }

  async function generateAgentOffer() {
    setBusy("agent");
    setFeedback(null);
    try {
      const offer = await actions.generateAgentOffer(workspace.dealId);
      setFeedback({
        tone: "info",
        message: `Demo agent added round ${offer.roundNumber}. This midpoint move was generated by the local demo, not by Spring AI.`,
      });
    } catch (error) {
      setFeedback({ tone: "error", message: error instanceof Error ? error.message : "The demo agent could not act." });
    } finally {
      setBusy(null);
    }
  }

  return (
    <div className="space-y-4">
      {frozen ? (
        <Alert tone="error" title="Negotiation is frozen">
          The deal is in dispute. Automated capture and acceptance are blocked by server state; offers and agreement
          changes are unavailable in this view.
        </Alert>
      ) : null}

      {feedback ? <Alert tone={feedback.tone}>{feedback.message}</Alert> : null}

      {workspace.myMandate ? (
        <>
          <MandateSummary
            mandate={workspace.myMandate}
            editing={editingMandate}
            onEdit={canEditMandate ? () => setEditingMandate((value) => !value) : undefined}
          />
          {editingMandate ? (
            <Card>
              <CardHeader
                title="Create a new mandate version"
                description="Existing offers are not rewritten. The server stores a new version against your identity."
              />
              <CardBody>
                <MandateBuilderForm
                  key={`mandate-${workspace.myMandate.mandateId}`}
                  initial={workspace.myMandate}
                  role={workspace.myRole}
                  onSubmit={saveMandate}
                  submitLabel="Save new mandate version"
                  disabled={!canEditMandate}
                  disabledReason="A mandate cannot be changed while the deal is frozen or closed."
                />
              </CardBody>
            </Card>
          ) : null}
        </>
      ) : (
        <Card>
          <CardHeader
            title="Lock your private mandate"
            description="A mandate turns your preferences into hard boundaries. The counterparty never sees it."
          />
          <CardBody>
            <MandateBuilderForm
              initial={null}
              role={workspace.myRole}
              onSubmit={saveMandate}
              submitLabel={`Lock ${workspace.myRole === "BUYER" ? "buyer" : "seller"} mandate`}
              disabled={!canEditMandate}
              disabledReason="A mandate can be locked during active negotiation or while terms are pending acceptance."
            />
          </CardBody>
        </Card>
      )}

      <Card>
        <CardHeader
          title="Offer comparison"
          description="Shared terms across rounds, with your private score and mandate check only."
          action={<span className="text-xs text-slate-500">{workspace.offers.length} visible rounds</span>}
        />
        <CardBody>
          <OfferComparison offers={workspace.offers} myRole={workspace.myRole} />
        </CardBody>
      </Card>

      {termsPending ? (
        <Alert
          tone="info"
          title="Terms are pending dual acceptance"
          action={
            <Button size="sm" variant="secondary" onClick={onOpenAgreement}>
              Review agreement
            </Button>
          }
        >
          New offers are paused while an agreement candidate exists. Review or accept the current agreement version.
        </Alert>
      ) : null}

      <Card>
        <CardHeader
          title={workspace.offers.length === 0 ? "Submit the first offer" : "Submit the next round"}
          description="Both roles can propose terms during active negotiation. The server checks them against your mandate."
        />
        <CardBody>
          {activeNegotiation ? (
            workspace.myMandate ? (
              <OfferForm
                key={`offer-form-${workspace.offers.length}-${workspace.myMandate.mandateId}`}
                initialTerms={initialTerms}
                mandate={workspace.myMandate}
                onSubmit={submitOffer}
                onGenerateAgent={generateAgentOffer}
                agentLoading={busy === "agent"}
                submitLabel={workspace.offers.length === 0 ? "Submit first offer" : "Submit counteroffer"}
              />
            ) : (
              <EmptyState
                title="Your mandate is required first"
                description="Lock your private boundaries above. The API rejects an offer from a party with no active mandate."
              />
            )
          ) : (
            <Alert tone="warning">
              {frozen
                ? "Offers are unavailable while the dispute freeze is active."
                : `New offers are not available while the deal is ${workspace.status.replaceAll("_", " ").toLowerCase()}.`}
            </Alert>
          )}
        </CardBody>
      </Card>

      <p className="text-xs leading-relaxed text-slate-500">
        Demo mode validates offers locally and labels scores as unscored. Live mode renders only the server&apos;s
        authenticated utility score and mandate result.
      </p>
    </div>
  );
}
